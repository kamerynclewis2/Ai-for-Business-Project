/**
 * Generates initials from a full name (e.g., "Marcus Davis" -> "MD")
 */
export function getInitials(name) {
  if (!name) return 'CR';
  const parts = name.trim().split(/\s+/);
  if (parts.length === 1) return parts[0].substring(0, 2).toUpperCase();
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

/**
 * Renders an executive initials avatar badge with tier styling
 */
export function renderInitialsAvatar(name, tier = 'default', size = 'md') {
  const initials = getInitials(name);
  const tierClass = tier ? `avatar-tier-${tier.toLowerCase()}` : 'avatar-tier-default';
  return `<div class="avatar-initials avatar-${size} ${tierClass}" title="${name}"><span>${initials}</span></div>`;
}
